// Select, crop, uniformly scale and pack generated sprites; never repaint/mask.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {sharp,inspectPoseAtlas} from './sprite-pose-inspector.mjs';
import {HERO_POSE_ART} from '../src/3d/hero-pose-data.js';
import {SKIN_POSE_ART} from '../src/3d/skin-pose-data.js';
import {HERO_INBETWEEN_ART} from '../src/3d/inbetween-data.js';
const root='assets/3d/fixed/long-motion/',write=process.argv.includes('--write');
const specs=JSON.parse(await fs.readFile('tools/long-motion-specs.json','utf8')),layouts={},results=[];
for(const [id,spec]of Object.entries(specs)){
  const identity=HERO_INBETWEEN_ART[id];assert.ok(identity,'known look');
  const base=identity.skin?SKIN_POSE_ART[id]:HERO_POSE_ART[id],targetHeight=base.frames[0].referenceHeight;
  const parts=spec.parts??[{source:id+'-v1.png',indices:Array.from({length:16},(_,i)=>i)}],selected=[];
  for(const part of parts){
    const source=root+'source/'+part.source,{layout}=await inspectPoseAtlas('',{id:part.source,source,delivery:source});
    const originalHeight=layout.frames.slice(0,4).map(f=>f.height).sort((a,b)=>a-b),scale=part.scale??targetHeight/((originalHeight[1]+originalHeight[2])/2);
    for(const index of part.indices){
      const original=layout.frames[index];assert.ok(original);let pixels=sharp(source).extract({left:original.left,top:original.top,width:original.width,height:original.height});
      const width=Math.max(1,Math.round(original.width*scale)),height=Math.max(1,Math.round(original.height*scale));
      if(width!==original.width||height!==original.height)pixels=pixels.resize(width,height,{kernel:'lanczos3'});
      selected.push({input:await pixels.png().toBuffer(),width,height,anchor:part.anchors?.[index]??original.anchor,referenceHeight:targetHeight,origin:{source,index,bounds:original,scale}});
    }
  }
  assert.equal(selected.length,16,id+' four directions × four new phases');
  const cw=Math.max(...selected.map(f=>f.width))+48,ch=Math.max(...selected.map(f=>f.height))+48,width=cw*4,height=ch*4,frames=[],pieces=[];
  for(const [i,f]of selected.entries()){
    const left=i%4*cw+Math.round((cw-f.width)/2),top=Math.floor(i/4)*ch+24;
    frames.push({left,top,width:f.width,height:f.height,anchor:f.anchor,anchorY:1,referenceHeight:f.referenceHeight});pieces.push({input:f.input,left,top});
  }
  const expected=await sharp({create:{width,height,channels:4,background:{r:0,g:0,b:0,alpha:0}}}).composite(pieces).png().toBuffer(),path=root+id+'-long-motion-v1.webp';
  if(write)await sharp(expected).webp({lossless:true,effort:6}).toFile(path);
  const before=await sharp(expected).ensureAlpha().raw().toBuffer(),after=await sharp(path).ensureAlpha().raw().toBuffer();assert.equal(before.length,after.length);
  let alphaDifferences=0,visibleRgbDifferences=0;for(let i=0;i<before.length;i+=4){if(before[i+3]!==after[i+3])alphaDifferences++;if(before[i+3])for(let c=0;c<3;c++)if(before[i+c]!==after[i+c])visibleRgbDifferences++;}
  assert.equal(alphaDifferences,0);assert.equal(visibleRgbDifferences,0);
  layouts[id]={heroId:identity.heroId,skin:identity.skin,path,width,height,roles:['compress-a','compress-b','early-follow','settle'],frames};
  results.push({id,path,sourcePoses:16,width,height,bytes:(await fs.stat(path)).size,alphaDifferences,visibleRgbDifferences,origins:selected.map(f=>f.origin)});
}
const source='// Generated by tools/long-motion-assets.mjs. Same-costume, display-only rows 8–11.\nexport const HERO_LONG_MOTION_ART = '+JSON.stringify(layouts,null,2)+';\n';
if(write)await fs.writeFile('src/3d/long-motion-data.js',source);else assert.equal(await fs.readFile('src/3d/long-motion-data.js','utf8'),source);
await fs.writeFile('docs/LONG_MOTION_ASSET_VALIDATION.json',JSON.stringify({generatedAt:new Date().toISOString(),looks:results.length,newPoses:results.length*16,losslessDelivery:true,operations:['exact crops','one uniform scale per source','transparent padding','packing'],results},null,2)+'\n');
console.log(JSON.stringify({looks:results.length,newPoses:results.length*16,bytes:results.reduce((n,r)=>n+r.bytes,0)}));
