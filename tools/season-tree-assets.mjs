#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {sharp,inspectPoseAtlas} from './sprite-pose-inspector.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source='assets/3d/fixed/source/season-trees-v1.png',delivery='assets/3d/fixed/season-trees-v1.webp';
if(process.argv.includes('--prepare'))await sharp(path.join(root,source)).webp({quality:91,alphaQuality:100,effort:6}).toFile(path.join(root,delivery));
const {layout,validation}=await inspectPoseAtlas(root,{id:'season-trees-v1',source,delivery,columns:3,rows:2});
// Props take their requested physical height; unlike character poses they do
// not share one actor's pixels-per-world-unit across different silhouettes.
for(const f of layout.frames)f.referenceHeight=f.height;
layout.indices={spring:[0,1],summer:[2,3],autumn:[4,5]};
assert.ok(validation.bytes<900000,'Six trees should fit in the prop atlas budget.');
const report={date:'2026-10-11',generation:'built-in imagegen; original PNG and full prompt preserved',processing:'WebP compression and pixel analysis only; alpha unchanged',...validation};
const dataPath=path.join(root,'src/3d/season-tree-data.js'),reportPath=path.join(root,'docs/SEASON_TREE_ASSET_VALIDATION.json');
if(process.argv.includes('--record')){
  await fs.writeFile(dataPath,'// Generated by tools/season-tree-assets.mjs --record.\nexport const SEASON_TREE_ART='+JSON.stringify(layout,null,2)+';\n');
  await fs.writeFile(reportPath,JSON.stringify(report,null,2)+'\n');
}else{
  const {SEASON_TREE_ART}=await import('../src/3d/season-tree-data.js');
  assert.deepEqual(layout,SEASON_TREE_ART,'Stored prop boundaries must match the original pixels.');
}
console.log(JSON.stringify({trees:layout.frames.length,bytes:validation.bytes,foreignVisiblePixels:validation.foreignVisiblePixels,uncoveredVisiblePixels:validation.uncoveredVisiblePixels,duplicateVisiblePixels:validation.duplicateVisiblePixels,outerBorderVisiblePixels:validation.outerBorderVisiblePixels,alphaDifferences:validation.alphaDifferences},null,2));
