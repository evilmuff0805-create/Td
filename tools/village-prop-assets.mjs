#!/usr/bin/env node
// Exact pixel bounds and lossless format conversion only. Never repaint art.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {sharp,inspectPoseAtlas} from './sprite-pose-inspector.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),layouts={},reports=[];
for(const [season,id]of [['temperate','village-props-v1'],['winter','village-props-winter-v1']]){
  const source=`assets/3d/fixed/source/${id}.png`,delivery=`assets/3d/fixed/${id}.webp`;
  if(process.argv.includes('--prepare'))await sharp(path.join(root,source)).webp({lossless:true,effort:6}).toFile(path.join(root,delivery));
  const {layout,validation}=await inspectPoseAtlas(root,{id,source,delivery,columns:3,rows:2});
  // Static props use the center of their ground footprint in every season.
  for(const f of layout.frames){f.referenceHeight=f.height;f.anchor=.5;}
  const raw=async rel=>(await sharp(path.join(root,rel)).ensureAlpha().raw().toBuffer());
  const [original,encoded]=await Promise.all([raw(source),raw(delivery)]);let visibleRGBDifferences=0;
  for(let p=0;p<original.length;p+=4)if(original[p+3]>=41)for(let c=0;c<3;c++)visibleRGBDifferences+=original[p+c]!==encoded[p+c];
  assert.equal(visibleRGBDifferences,0,id+' visible colors unchanged');
  assert.ok(validation.bytes<1500000,id+' delivery budget');
  layouts[season]=layout;reports.push({...validation,season,visibleRGBDifferences,anchorPolicy:'centered static footprint; lowest visible pixel at ground'});
}
const report={date:'2026-10-11',generation:'built-in imagegen; originals and exact prompts preserved',processing:'lossless WebP conversion and alpha-component bounds only; no repainting',props:12,deliveryBytes:reports.reduce((n,r)=>n+r.bytes,0),atlases:reports};
if(process.argv.includes('--record')){
  await fs.writeFile(path.join(root,'src/3d/village-prop-data.js'),'// Generated by tools/village-prop-assets.mjs --record.\nexport const VILLAGE_PROP_ART='+JSON.stringify(layouts,null,2)+';\n');
  await fs.writeFile(path.join(root,'docs/VILLAGE_PROP_ASSET_VALIDATION.json'),JSON.stringify(report,null,2)+'\n');
}else{
  const {VILLAGE_PROP_ART}=await import('../src/3d/village-prop-data.js');
  assert.deepEqual(layouts,VILLAGE_PROP_ART,'Saved bounds must reproduce original pixels.');
}
console.log(JSON.stringify({props:12,deliveryBytes:report.deliveryBytes,visibleRGBDifferences:0,alphaDifferences:0,foreignVisiblePixels:0,uncoveredVisiblePixels:0,duplicateVisiblePixels:0,outerBorderVisiblePixels:0},null,2));
