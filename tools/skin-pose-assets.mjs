import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {sharp,inspectPoseAtlas} from './sprite-pose-inspector.mjs';
sharp.concurrency(2);
const root=fileURLToPath(new URL('../',import.meta.url));
const specs=JSON.parse(await fs.readFile(path.join(root,'tools/skin-pose-specs.json'),'utf8'));
const recordIndex=process.argv.indexOf('--record'),record=recordIndex>=0?process.argv[recordIndex+1]:null;
const layouts={},units=[];
for(const spec of specs){
  if(record&&record!==spec.id)continue;
  const name=`${spec.id}-directions-v${spec.version}`,base='assets/3d/fixed/skins/',source=base+'source/'+name+'.png',delivery=base+name+'.webp';
  if(record){
    const prompt=JSON.parse(await fs.readFile(path.join(root,base+name+'.prompt.json'),'utf8'));
    if(!prompt.generatedFile)throw new Error('Record the generated original filename before importing '+spec.id);
    const generated=path.join('C:/Users/USER/.codex/generated_images/01a1208e-1f21-7ee1-8355-345389c0c96c',prompt.generatedFile);
    await fs.mkdir(path.dirname(path.join(root,source)),{recursive:true});
    await fs.copyFile(generated,path.join(root,source));
    await sharp(path.join(root,source)).webp({quality:90,alphaQuality:100,effort:6}).toFile(path.join(root,delivery));
  }
  const result=await inspectPoseAtlas(root,{id:spec.id,source,delivery,pivotXOverrides:spec.pivotXOverrides});
  layouts[spec.id]=result.layout;units.push({...result.validation,heroId:spec.heroId,name:spec.name});
  console.log(`${spec.id}: 16 poses, clean rectangles, ${result.validation.bytes} bytes`);
}
if(record){if(!units.length)throw new Error('Unknown costume: '+record);process.exit(0);}
const report={date:'2026-10-11',generation:'built-in imagegen edits of approved hero sheets; original PNG and alpha preserved',analysis:'alpha >=16 connected components; visible foreign/omitted/duplicate pixels checked at alpha >=41; lower 24% alpha-weighted foot baseline',units,totalPoses:units.length*16,totalDeliveryBytes:units.reduce((n,u)=>n+u.bytes,0)};
if(process.argv.includes('--write')){
  await fs.writeFile(path.join(root,'src/3d/skin-pose-data.js'),'// Generated by node tools/skin-pose-assets.mjs --write. Literal paths support standalone embedding.\nexport const SKIN_POSE_ART = '+JSON.stringify(layouts,null,2)+';\n');
  await fs.writeFile(path.join(root,'docs/SKIN_POSE_ASSET_VALIDATION.json'),JSON.stringify(report,null,2)+'\n');
}else{
  const {SKIN_POSE_ART}=await import('../src/3d/skin-pose-data.js');
  if(JSON.stringify(SKIN_POSE_ART)!==JSON.stringify(layouts))throw new Error('Stored costume pose metadata is stale; inspect artwork before --write');
}
console.log(`Validated ${units.length} costumes, ${report.totalPoses} poses; ${report.totalDeliveryBytes} bytes.`);
