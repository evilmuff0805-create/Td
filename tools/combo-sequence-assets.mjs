// Repack complete image cells with transparent gutters. No painting or masking.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {sharp} from './sprite-pose-inspector.mjs';
const specs=JSON.parse(await fs.readFile('tools/combo-sequence-specs.json','utf8')),write=process.argv.includes('--write'),sequences={},results=[];
function cuts(size,cost){
  const result=[0];for(let i=1;i<4;i++){
    const ideal=Math.round(size*i/4),range=Math.round(size/4*.15);let best=ideal,bestCost=Infinity;
    for(let p=ideal-range;p<=ideal+range;p++){const n=cost(p)+cost(p-1);if(n<bestCost||(n===bestCost&&Math.abs(p-ideal)<Math.abs(best-ideal))){best=p;bestCost=n;}}
    assert.equal(bestCost,0,'Visible effect crosses all candidate cell cuts at '+ideal);result.push(best);
  }result.push(size);return result;
}
for(const [id,spec]of Object.entries(specs)){
  assert.equal(spec.projection,'ground','Only actual top-down ground art is accepted');
  assert.equal(spec.origins?.length,16,'Authored semantic ground origins are required, never a changing halo centroid');
  const source='assets/3d/fixed/combo-sequences/source/'+spec.source,{data,info}=await sharp(source).ensureAlpha().raw().toBuffer({resolveWithObject:true}),{width,height}=info;
  const visible=(x,y)=>data[(y*width+x)*4+3]>=16;
  for(let x=0;x<width;x++)assert.ok(!visible(x,0)&&!visible(x,height-1),id+' source outer edge');
  for(let y=0;y<height;y++)assert.ok(!visible(0,y)&&!visible(width-1,y),id+' source outer edge');
  const ys=cuts(height,y=>{let n=0;for(let x=0;x<width;x++)if(visible(x,y))n++;return n;}),cells=[];
  for(let row=0;row<4;row++){
    const xs=cuts(width,x=>{let n=0;for(let y=ys[row];y<ys[row+1];y++)if(visible(x,y))n++;return n;});
    for(let col=0;col<4;col++)cells.push({left:xs[col],top:ys[row],width:xs[col+1]-xs[col],height:ys[row+1]-ys[row]});
  }
  const padding=32,cw=Math.max(...cells.map(c=>c.width))+padding*2,ch=Math.max(...cells.map(c=>c.height))+padding*2,pieces=[],frames=[];
  for(const [frame,c]of cells.entries()){
    let painted=0;for(let y=0;y<c.height;y++)for(let x=0;x<c.width;x++)if(data[((y+c.top)*width+x+c.left)*4+3]>=16)painted++;
    assert.ok(painted>100,id+' frame '+frame+' needs generated artwork');
    const left=frame%4*cw+Math.floor((cw-c.width)/2),top=Math.floor(frame/4)*ch+Math.floor((ch-c.height)/2);
    const [ox,oy]=spec.origins[frame];assert.ok(ox>=c.left&&ox<c.left+c.width&&oy>=c.top&&oy<c.top+c.height,id+' semantic origin is inside its own cell');
    pieces.push({input:await sharp(source).extract(c).png().toBuffer(),left,top});
    frames.push({frame,sourceBounds:c,sourceOrigin:{x:ox,y:oy},anchorFeature:spec.anchorFeature,paintedPixels:painted,minimumPadding:padding,pivot:{x:+((left%cw+ox-c.left)/cw).toFixed(6),y:+((top%ch+oy-c.top)/ch).toFixed(6)}});
  }
  const expected=await sharp({create:{width:cw*4,height:ch*4,channels:4,background:{r:0,g:0,b:0,alpha:0}}}).composite(pieces).png().toBuffer(),path='assets/3d/fixed/combo-sequences/'+id+'-sequence-v1.webp';
  if(write)await sharp(expected).webp({lossless:true,effort:6}).toFile(path);
  const before=await sharp(expected).ensureAlpha().raw().toBuffer(),after=await sharp(path).ensureAlpha().raw().toBuffer();assert.equal(before.length,after.length);
  let alphaDifferences=0,visibleRgbDifferences=0;for(let i=0;i<before.length;i+=4){if(before[i+3]!==after[i+3])alphaDifferences++;if(before[i+3])for(let c=0;c<3;c++)if(before[i+c]!==after[i+c])visibleRgbDifferences++;}
  assert.equal(alphaDifferences,0);assert.equal(visibleRgbDifferences,0);
  sequences[id]={path,width:cw*4,height:ch*4,columns:4,rows:4,frames:16,projection:spec.projection,pivots:frames.map(f=>f.pivot)};
  results.push({id,source,path,bytes:(await fs.stat(path)).size,alphaDifferences,visibleRgbDifferences,frames});
}
const output='// Generated by tools/combo-sequence-assets.mjs. Dedicated combo artwork with per-atlas layout.\nexport const COMBO_SEQUENCES = '+JSON.stringify(sequences,null,2)+';\n';
if(write)await fs.writeFile('src/3d/combo-sequence-data.js',output);else assert.equal(await fs.readFile('src/3d/combo-sequence-data.js','utf8'),output);
await fs.writeFile('docs/COMBO_SEQUENCE_ASSET_VALIDATION.json',JSON.stringify({generatedAt:new Date().toISOString(),combos:results.length,frames:results.length*16,losslessDelivery:true,minimumPadding:32,originalPixelsRepainted:false,results},null,2)+'\n');
console.log(JSON.stringify({combos:results.length,frames:results.length*16,bytes:results.reduce((n,r)=>n+r.bytes,0)}));
