// Inspect generated pixels and encode losslessly. No repainting/masking/resizing.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { sharp } from './sprite-pose-inspector.mjs';
const elements={},results=[];
for(const family of ['fire','flood','heal']){
  const source=`assets/3d/fixed/source/combo-${family}-v1.png`,path=`assets/3d/fixed/combo-${family}-v1.webp`;
  const before=await sharp(source).ensureAlpha().raw().toBuffer({resolveWithObject:true}),{width,height}=before.info;
  assert.equal(width,height*2);
  const frames=[];
  for(let frame=0;frame<8;frame++){
    const x0=Math.round(frame%4*width/4),x1=Math.round((frame%4+1)*width/4),y0=Math.round(Math.floor(frame/4)*height/2),y1=Math.round((Math.floor(frame/4)+1)*height/2),cw=x1-x0,ch=y1-y0;let left=cw,top=ch,right=-1,bottom=-1,visible=0,boundaryPixels=0;
    for(let y=0;y<ch;y++)for(let x=0;x<cw;x++)if(before.data[((y+y0)*width+x+x0)*4+3]>=16){visible++;left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);if(x===0||x===cw-1||y===0||y===ch-1)boundaryPixels++;}
    assert.ok(visible>100,`${family}/${frame}: painted content`);assert.equal(boundaryPixels,0,`${family}/${frame}: no clipped edge`);
    const gutter=Math.min(left,top,cw-1-right,ch-1-bottom);assert.ok(gutter>=12,`${family}/${frame}: transparent gutter ${gutter}`);
    frames.push({frame,visiblePixels:visible,minimumTransparentGutter:gutter,boundaryPixels,pivot:{x:+((left+right+1)/2/cw).toFixed(6),y:+((top+bottom+1)/2/ch).toFixed(6)}});
  }
  await sharp(source).webp({lossless:true,effort:6}).toFile(path);
  const after=await sharp(path).ensureAlpha().raw().toBuffer({resolveWithObject:true});let alphaDifferences=0,visibleRgbDifferences=0;
  assert.equal(after.info.width,width);assert.equal(after.info.height,height);
  for(let i=0;i<before.data.length;i+=4){if(before.data[i+3]!==after.data[i+3])alphaDifferences++;if(before.data[i+3]>0)for(let c=0;c<3;c++)if(before.data[i+c]!==after.data[i+c])visibleRgbDifferences++;}
  assert.equal(alphaDifferences,0);assert.equal(visibleRgbDifferences,0);
  elements[family]={path,columns:4,rows:2,frames:8,pivots:frames.map(f=>f.pivot)};
  results.push({family,source,path,width,height,bytes:(await fs.stat(path)).size,alphaDifferences,visibleRgbDifferences,frames});
}
await fs.writeFile('src/3d/combo-element-data.js','// Generated by tools/combo-element-assets.mjs; original generated pixels are unchanged.\nexport const COMBO_ELEMENTS = '+JSON.stringify(elements,null,2)+';\n');
await fs.writeFile('docs/COMBO_ELEMENT_ASSET_VALIDATION.json',JSON.stringify({date:'2026-10-11',lossless:true,results},null,2)+'\n');
console.log(JSON.stringify(results.map(({family,width,height,bytes})=>({family,width,height,bytes})),null,2));
